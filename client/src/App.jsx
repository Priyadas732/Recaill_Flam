import React from 'react';
import { useSession } from './context/SessionContext.jsx';
import { STAGES } from './models/constants.js';
import { TopBar } from './views/components/layout/TopBar.jsx';
import { InputPage } from './views/pages/InputPage.jsx';
import { LessonPage } from './views/pages/LessonPage.jsx';
import { QuizPage } from './views/pages/QuizPage.jsx';
import { ReportPage } from './views/pages/ReportPage.jsx';
import { ReviewPage } from './views/pages/ReviewPage.jsx';

export default function App() {
  const { state } = useSession();

  const renderCurrentPage = () => {
    switch (state.stage) {
      case STAGES.INPUT:
        return <InputPage />;
      case STAGES.LESSON:
        return <LessonPage />;
      case STAGES.QUIZ:
        return <QuizPage />;
      case STAGES.REPORT:
        return <ReportPage />;
      case STAGES.REVIEW:
        return <ReviewPage />;
      default:
        return <InputPage />;
    }
  };

  return (
    <div className="min-h-screen flex flex-col justify-between selection:bg-secondary-container selection:text-on-secondary-container">
      <TopBar />

      <div className="flex-1 flex flex-col">
        {renderCurrentPage()}
      </div>

      {/* Global Academic Footer Shell */}
      <footer className="w-full py-6 px-6 border-t border-outline-variant/30 dark:border-white/10 mt-auto">
        <div className="max-w-[1120px] mx-auto flex flex-col md:flex-row items-center justify-between gap-4 text-center md:text-left">
          <div className="font-body-sm text-xs text-on-surface-variant/70 dark:text-outline-variant/70">
            Recall AI · Responses generated by AI may vary in accuracy. Verify critical facts.
          </div>
          <div className="flex items-center gap-5 text-xs font-label-md text-label-md">
            <a className="text-on-surface-variant/70 hover:text-[#447F98] transition-colors" href="#honor">
              Honor Code
            </a>
            <span className="text-outline-variant/40">·</span>
            <a className="text-on-surface-variant/70 hover:text-[#447F98] transition-colors" href="#terms">
              Terms of Study
            </a>
            <span className="text-outline-variant/40">·</span>
            <a className="text-on-surface-variant/70 hover:text-[#447F98] transition-colors" href="#privacy">
              Privacy
            </a>
          </div>
        </div>
      </footer>
    </div>
  );
}
